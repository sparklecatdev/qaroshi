#!/usr/bin/env python3
"""Offline Chromium UI tests for the v21–23 combined language workspace."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[2]
from restore_artifacts import restore
restore()
HTML=(ROOT/'Qaroshi_21_23_Translation_Immersion_Academy.html').read_text(encoding='utf8')
checks=[]
def ok(condition,message):
 if not condition:raise AssertionError(message)
 checks.append(message)
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-gpu'])
 for mode,view in [('desktop',{'width':1440,'height':900}),('mobile',{'width':390,'height':850})]:
  page=browser.new_page(viewport=view);errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  page.set_content(HTML,wait_until='domcontentloaded',timeout=90000)
  ok(page.locator('#stats .stat').count()==3,mode+' source summary')
  ok(page.locator('.nav .tab').count()==6,mode+' six sections')
  ok(page.locator('#translate').is_visible(),mode+' initial translate')
  page.locator('#sourceInput').fill('hë ti haro he?')
  page.locator('#translateBtn').click()
  ok('EXACT DOCUMENTED' in page.locator('#translationResult').inner_text(),mode+' exact source translation')
  ok('Are you well?' in page.locator('#translationResult').inner_text(),mode+' translated text')
  ok(page.locator('#translationResult a.wordlink').count()>=2,mode+' click through to lexical roots')
  page.locator('#sourceInput').fill('The moon invented a quantum zucchini rocket yesterday.')
  page.locator('#direction').select_option('en');page.locator('#translateBtn').click()
  ok('No exact bilingual source match' in page.locator('#translationResult').inner_text(),mode+' explicit translation abstention')
  page.locator('#sourceInput').fill('hë ti haro he?');page.locator('#direction').select_option('qr');page.locator('#translateBtn').click()
  page.locator('#translationResult .wordlink').first.click()
  page.locator('#words').wait_for(state='visible')
  ok(page.locator('#wordDetail h2').count()==1,mode+' dictionary deep link')
  ok(page.evaluate('location.hash').startswith('#word/'),mode+' bookmarkable word link')
  page.locator('#navBack').click();page.locator('#translate').wait_for(state='visible')
  ok(page.locator('#translate').is_visible(),mode+' in-app back')
  page.locator('[data-route="reader"]').click();page.locator('#reader').wait_for(state='visible')
  ok(page.locator('#readingList .itemlink').count()==108,mode+' comprehensive reading catalog')
  page.locator('#readingBand').select_option('stretch')
  ok(10<page.locator('#readingList .itemlink').count()<108,mode+' difficulty filtering')
  page.locator('#readingBand').select_option('');page.locator('#readingSearch').fill('Archive')
  ok(page.locator('#readingList .itemlink').count()>=1,mode+' story search')
  page.locator('#readingList .itemlink').first.click()
  page.locator('#readingDetail h2').wait_for()
  ok(page.locator('#readingDetail .record').count()>=6,mode+' aligned original reading')
  ok(page.locator('#readingDetail .wordlink').count()>=8,mode+' inline root links')
  page.locator('#readingDetail .record button').first.click()
  ok(page.locator('#readingDetail .record .en').count()==1,mode+' single-line context reveal')
  page.locator('#readingDetail button').filter(has_text='Show all English').click()
  ok(page.locator('#readingDetail .record .en').count()>=6,mode+' reveal-all reading')
  page.locator('#readingDetail a[href^="#quiz/"]').first.click()
  page.locator('#quiz').wait_for(state='visible')
  ok(page.locator('#quizBody .qoption').count()==4,mode+' four source recognition choices')
  page.locator('#quizBody .qoption').first.click()
  ok(page.locator('#quizBody .notice').count()==1,mode+' feedback after first answer')
  ok('1/3 answered' in page.locator('#quizProgress').inner_text(),mode+' local progress stored')
  page.locator('#quizNext').click()
  ok(page.locator('#quizBody .qoption').count()==4,mode+' next question')
  ok(page.locator('#modules .record').count()==12,mode+' twelve actionable modules')
  page.locator('#modules .record button').first.click()
  ok('✓ Practiced' in page.locator('#modules .record button').first.inner_text(),mode+' personal module completion')
  page.locator('#globalSearch').fill('consent')
  ok(page.locator('#globalResults').is_visible(),mode+' unified search')
  ok(page.locator('#globalResults a').count()>=2,mode+' sourced search suggestions')
  page.locator('#globalSearch').press('Escape');ok(page.locator('#globalResults').is_hidden(),mode+' search escape shortcut')
  page.locator('[data-route="review"]').click();page.locator('#review').wait_for(state='visible')
  ok(page.locator('#reviewList .itemlink').count()==103,mode+' 103 prior translation discrepancies')
  page.locator('#reviewList .itemlink').first.click()
  ok('Unapproved proposed standalone reading' in page.locator('#reviewDetail').inner_text(),mode+' context versus unapproved proposal')
  page.locator('#reviewChoice').select_option('needs_context')
  page.locator('#reviewNote').fill('Check the overtly encoded predicate with a separate reader.')
  page.locator('#reviewDetail button.primary').click()
  ok('Saved locally' in page.locator('#reviewSaved').inner_text(),mode+' private editorial review notes')
  page.locator('[data-route="about"]').click();page.locator('#about').wait_for(state='visible')
  ok('not empirically calibrated' in page.locator('#about').inner_text(),mode+' clear grading limitations')
  ok(not errors,mode+' no JavaScript errors: '+str(errors[:2]))
  page.locator('[data-route="translate"]').click()
  if mode=='desktop':page.screenshot(path=str(ROOT/'Qaroshi_21_23_Desktop_Preview.png'),full_page=True)
  else:page.screenshot(path=str(ROOT/'Qaroshi_21_23_Mobile_Preview.png'),full_page=True)
  if mode=='mobile':
   b=page.locator('.nav .tab').evaluate_all('(xs)=>xs.map(x=>({left:x.getBoundingClientRect().left,right:x.getBoundingClientRect().right}))')
   ok(all(x['left']>=0 and x['right']<=view['width'] for x in b),mode+' all nav tabs fit width')
  page.close()
 browser.close()
(ROOT/'data/v23/browser_checks.json').write_text(json.dumps({'passed':True,'checks':len(checks),'cases':checks},indent=2),encoding='utf8')
print('PASSED',len(checks),'desktop/mobile browser checks')
