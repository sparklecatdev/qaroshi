"""UI smoke tests for self-contained v15 corpus library. Chromium via Playwright."""
from pathlib import Path
from playwright.sync_api import sync_playwright
import json
ROOT=Path(__file__).resolve().parents[2]
HTML=(ROOT/'Qaroshi_15_Corpus_Library.html').read_text(encoding='utf8')
checks=[];errors=[]
def ck(name,condition):
 checks.append((name,bool(condition)))
 if not condition:print('FAIL:',name)
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-web-security'])
 page=b.new_page(viewport={'width':1390,'height':900})
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content(HTML,wait_until='load',timeout=90000)
 ck('library title', 'A language in context' in page.locator('#main').inner_text())
 ck('154 conversations number', '176' in page.locator('#main').inner_text())
 ck('filters',page.locator('#kindFilter').count()==1)
 page.locator('#kindFilter').select_option('literature')
 ck('literature filtering', '35 pieces' in page.locator('#main').inner_text())
 page.locator('#kindFilter').select_option('dialogue')
 ck('dialogue filtering', '176 pieces' in page.locator('#main').inner_text())
 page.locator('#sourceFilter').select_option('15.0')
 ck('new 15.0 filters', '73 pieces' in page.locator('#main').inner_text())
 page.locator('[data-piece]').first.click()
 ck('detail',page.locator('.line').count()>=5)
 ck('IPA visible',page.locator('.ipa').count()>=5)
 ck('English initially hidden',page.locator('details.english-detail[open]').count()==0)
 page.locator('#translateBtn').click()
 ck('translations revealed',page.locator('details.english-detail[open]').count()==page.locator('.line').count())
 page.locator('#reviewText').fill('Needs a human semantic check of tense and pronouns.')
 page.locator('#saveReview').click()
 ck('review saved',page.locator('#reviewText').input_value().startswith('Needs a human'))
 page.locator('[data-word]').first.click()
 ck('word lookup', '30,000-word dictionary' in page.locator('#main').inner_text())
 page.locator('[data-conc]').first.click()
 ck('concordance', 'Concordance' in page.locator('#main').inner_text())
 page.locator('[data-section="review"]').click()
 ck('review exported',page.locator('#exportBtn').count()==1)
 page.locator('[data-section="about"]').click()
 ck('methodology', 'independently' in page.locator('#main').inner_text().lower())
 page.locator('[data-section="library"]').click()
 page.locator('#globalSearch').fill('star')
 page.locator('#globalSearch').press('Enter')
 ck('global search',page.locator('[data-piece]').count()>0)
 page.screenshot(path=str(ROOT/'Qaroshi_15_Desktop_Preview.png'),full_page=False)
 mobile=b.new_page(viewport={'width':390,'height':844},is_mobile=True)
 mobile.on('pageerror',lambda e:errors.append(str(e)))
 mobile.set_content(HTML,wait_until='load',timeout=90000)
 mobile.locator('#menubtn').click()
 ck('mobile menu',mobile.locator('#sidebar').evaluate('(e)=>e.classList.contains("open")'))
 mobile.locator('[data-section="library"]').click()
 ck('mobile library',mobile.locator('h1').count()==1)
 mobile.screenshot(path=str(ROOT/'Qaroshi_15_Mobile_Preview.png'),full_page=False)
 b.close()
print('CHECKS',sum(x[1] for x in checks),'/',len(checks),'errors',errors)
(ROOT/'data/v15/browser_test_report.json').write_text(json.dumps({'checks':checks,'page_errors':errors,'passed':all(v for _,v in checks) and not errors},indent=2),encoding='utf8')
if errors or not all(x for _,x in checks):raise SystemExit(1)
