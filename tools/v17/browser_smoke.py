#!/usr/bin/env python3
"""Verify offline v17 HTML in Chromium, both desktop and mobile viewports."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[2]
HTML=(ROOT/'Qaroshi_17_Everyday_Communicator.html').read_text(encoding='utf8')
report=[]
def ck(flag,what):
 if not flag:raise AssertionError(what)
 report.append(what)
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-gpu'])
 for viewport in ({'width':1440,'height':960},{'width':393,'height':852}):
  page=browser.new_page(viewport=viewport)
  err=[];page.on('pageerror',lambda e:err.append(str(e)))
  page.set_content(HTML,wait_until='domcontentloaded',timeout=90000)
  kind='mobile' if viewport['width']<600 else 'desktop'
  ck(page.locator('#stats .stat').count()==6,kind+' stats')
  ck(page.locator('#starter .phrase').count()==6,kind+' six essential phrases')
  ck(page.locator('#lessonSummary .bubble').count()==10,kind+' learning path')
  page.locator('[data-nav="phrases"]').click()
  ck(page.locator('#phraseCards .phrase').count()==24,kind+' phrase pagination')
  page.locator('#phraseSearch').fill('consent')
  ck(page.locator('#phraseCards .phrase').count()>=2,kind+' consent phrase search')
  page.locator('#phraseSearch').fill('')
  page.locator('#phraseCards [data-action="favorite"]').first.click()
  page.locator('#favoriteOnly').check()
  ck(page.locator('#phraseCards .phrase').count()==1,kind+' favorite filter')
  page.locator('#favoriteOnly').uncheck()
  page.locator('#phraseReset').click()
  page.locator('#morePhrases').click()
  ck(page.locator('#phraseCards .phrase').count()==48,kind+' phrase load more')
  page.locator('[data-nav="missions"]').click()
  ck(page.locator('#missionSelect option').count()>=25,kind+' scripted dialogue collection')
  page.locator('#revealTurn').click()
  ck(page.locator('#missionDisplay').inner_text().find('Contextual English:')>=0,kind+' reveal contextual translation')
  page.locator('#missionNext').click()
  ck('Line 2 of' in page.locator('#missionProgress').inner_text(),kind+' next dialogue turn')
  page.locator('[data-nav="builder"]').click()
  ck('sen mi goro.' in page.locator('#buildResult').inner_text(),kind+' controlled builder default')
  page.locator('#buildSubject').select_option('ti')
  page.locator('#buildModal').select_option('-ki')
  page.locator('#buildQuestion').check()
  ck('ti goro-ki he?' in page.locator('#buildResult').inner_text(),kind+' ability + question pattern')
  page.locator('#buildModal').select_option('-ho')
  ck('goro-ho he?' in page.locator('#buildResult').inner_text(),kind+' permission distinction')
  page.locator('#buildVerb').select_option('këmë')
  ck('kima-m' in page.locator('#buildResult').inner_text(),kind+' direct object -m')
  page.locator('#buildNegative').check()
  ck(' nu ' in page.locator('#buildResult').inner_text(),kind+' negative placement')
  page.locator('[data-nav="script"]').click()
  ck(page.locator('#resonanceCards .panel').count()==16,kind+' sixteen resonance cards')
  ck(page.locator('#nativeOutput img').count()>=5,kind+' original native glyph rendering')
  page.locator('#scriptInput').fill('kh ng sh zh ë')
  ck(page.locator('#nativeOutput img').count()==5,kind+' four single native digraphs and ë')
  page.locator('#accentKey').click()
  ck('ë' in page.locator('#scriptInput').input_value(),kind+' accent input')
  page.locator('[data-nav="dictionary"]').click()
  page.locator('#dictionarySearch').fill('kima')
  ck(page.locator('#dictionaryCards .phrase').count()>=1,kind+' dictionary search')
  page.locator('#dictCoreOnly').click()
  ck(page.locator('#dictionaryCards .phrase').count()>=1 or '0 results' in page.locator('#dictionaryCount').inner_text(),kind+' core root filter')
  page.locator('[data-nav="study"]').click()
  ck(page.locator('#lessonSelect option').count()==10,kind+' ten recall drills')
  page.locator('#lessonReveal').click()
  ck(page.locator('#lessonDisplay .bigqr').count()==1,kind+' reveal recall answer')
  page.locator('#lessonKnown').click()
  ck(page.locator('#knownTotal').inner_text()=='1',kind+' local skill counter')
  page.locator('[data-nav="about"]').click()
  ck('not a certified' in page.locator('#about').inner_text(),kind+' explicit editorial limitations')
  ck(not err,kind+' zero JavaScript errors: '+str(err[:3]))
  page.locator('[data-nav="start"]').click()
  if kind=='desktop':page.screenshot(path=str(ROOT/'Qaroshi_17_Desktop.png'),full_page=True)
  else:page.screenshot(path=str(ROOT/'Qaroshi_17_Mobile.png'),full_page=True)
  page.close()
 browser.close()
(ROOT/'data/v17/browser_report.json').write_text(json.dumps({'checks':len(report),'passed':True,'checks_list':report},indent=2),encoding='utf8')
print('PASSED',len(report),'browser interactions')
