#!/usr/bin/env python3
"""Run desktop/mobile browser interaction checks on the self-contained offline HTML."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[2]
html=(ROOT/'Qaroshi_Fluency_11.html').read_text(encoding='utf8')
checks=[];errors=[]
def check(name,condition):
    checks.append({'name':name,'passed':bool(condition)})
    if not condition:raise AssertionError(name)
with sync_playwright() as pw:
    b=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=b.new_page(viewport={'width':1420,'height':980},device_scale_factor=1)
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content(html,wait_until='load',timeout=60000)
    check('overview loads',page.locator('h1').inner_text()=='Speak with meaning.')
    check('navigation entries',page.locator('#nav button').count()==9)
    page.locator('#nav [data-go="translate"]').click()
    page.locator('#runTranslate').click()
    check('English to Qaroshi licensed translation','goro-ki' in page.locator('#translateOut').inner_text())
    page.locator('#dir').select_option('qr')
    page.locator('#translateInput').fill('sen mi kima-m nu këmë.')
    page.locator('#runTranslate').click()
    check('Qaroshi to English licensed translation','do not drink water' in page.locator('#translateOut').inner_text().lower())
    page.locator('#translateInput').fill('sen mi qwwfoo.')
    page.locator('#runTranslate').click()
    check('no hallucinated unknown sentence','No full licensed translation found' in page.locator('#translateOut').inner_text())
    page.locator('#tryExample').click()
    check('complex exact reference','Please never die' in page.locator('#translateOut').inner_text())
    page.locator('#nav [data-go="builder"]').click()
    page.locator('#buildNow').click()
    check('sentence builder emits Qaroshi','sen mi goro.' in page.locator('#buildOut').inner_text())
    page.locator('#buildTone').select_option('më')
    page.locator('#buildNow').click()
    check('builder respects selected resonance','më mi goro.' in page.locator('#buildOut').inner_text())
    page.locator('#nav [data-go="reading"]').click()
    page.locator('#sceneSelect').wait_for()
    check('dialogue turns are displayed',page.locator('.dialogue .item').count()==6)
    page.locator('#revealAll').click()
    check('dialogue translations reveal',page.locator('details.meaning[open]').count()==6)
    page.locator('#nextScene').click()
    check('next scene changes selection',page.locator('#sceneSelect').input_value()=='1')
    page.locator('#markRead').click()
    check('reading progress marker','Practiced' in page.locator('#markRead').inner_text())
    page.locator('#nav [data-go="literature"]').click()
    page.locator('#textChoice').wait_for()
    check('literary source list',page.locator('#textChoice option').count()==5)
    page.locator('#revealText').click()
    check('literary translations reveal',page.locator('details.textline[open]').count()==10)
    page.locator('#nav [data-go="study"]').click()
    page.locator('[data-start="q1"]').wait_for()
    check('five proficiency levels',page.locator('[data-start]').count()==5)
    page.locator('[data-start="q1"]').click()
    check('test begins','Question 1 of 20' in page.locator('#main h1').inner_text())
    for i in range(20):
        page.locator('[data-answer]').first.click()
        check('quiz explanation displayed '+str(i+1),page.locator('#feedback').count()==1 and bool(page.locator('#feedback').inner_text().strip()))
        page.locator('#continue').click()
    check('assessment outcome','Practice milestone' in page.locator('#main').inner_text() or 'Practice completed' in page.locator('#main').inner_text())
    page.locator('#nav [data-go="dictionary"]').click()
    page.locator('#dictSearch').fill('goro')
    check('dictionary search',page.locator('#dictResults .item').count()>0)
    page.locator('#nav [data-go="alphabet"]').click()
    page.locator('#glyphText').wait_for()
    check('all original glyphs rendered',page.locator('img.glyph').count()>=26)
    page.locator('#glyphText').fill('sh zh kh ng ë')
    check('digraph conversion to five glyphs',page.locator('#glyphOutput img').count()==5)
    page.locator('#theme').click()
    check('dark mode',page.locator('html').get_attribute('data-dark')=='true')
    page.locator('#nav [data-go="about"]').click()
    page.locator('#exportProgress').wait_for()
    check('progress export control',page.locator('#exportProgress').count()==1)
    with page.expect_download() as d:page.locator('#exportProgress').click()
    check('progress exported',d.value.suggested_filename=='qaroshi11_progress.json')
    page.locator('#nav [data-go="home"]').click()
    page.screenshot(path=str(ROOT/'Qaroshi_11_Desktop_Preview.png'),full_page=True)
    mobile=b.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
    mobile.on('pageerror',lambda e:errors.append(str(e)))
    mobile.set_content(html,wait_until='load',timeout=60000)
    check('mobile home',mobile.locator('h1').inner_text()=='Speak with meaning.')
    mobile.locator('#menu').click()
    check('mobile menu opens','open' in mobile.locator('#sidebar').get_attribute('class'))
    mobile.locator('#nav [data-go="reading"]').click()
    mobile.locator('#sceneSelect').wait_for()
    check('mobile scene navigation',mobile.locator('#sceneSelect option').count()>=45)
    mobile.wait_for_timeout(350)
    mobile.screenshot(path=str(ROOT/'Qaroshi_11_Mobile_Preview.png'),full_page=True)
    b.close()
report={'total_checks':len(checks),'passed':sum(x['passed'] for x in checks),'page_errors':errors,'checks':checks}
(ROOT/'data/fluency11/browser_report.json').write_text(json.dumps(report,indent=2),encoding='utf8')
print(json.dumps({k:report[k] for k in ('total_checks','passed','page_errors')},indent=2))
if errors or any(not x['passed'] for x in checks):raise SystemExit(1)
