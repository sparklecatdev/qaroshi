#!/usr/bin/env python3
"""Headless desktop/mobile smoke for the self-contained Qaroshi 14 dashboard."""
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[2]
HTML=(ROOT/'Qaroshi_14_Semantic_Workbench.html').read_text(encoding='utf8')
checks=[];errors=[]
def ck(n,x):
 x=bool(x);checks.append((n,x));print(('PASS' if x else 'FAIL')+' '+n)
with sync_playwright() as pw:
 browser=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1350,'height':900},accept_downloads=True)
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content(HTML,wait_until='domcontentloaded',timeout=80000)
 ck('home',page.locator('h1').inner_text()=='Consistency before expansion.')
 ck('four overview metrics',page.locator('.metric').count()==4)
 page.screenshot(path=str(ROOT/'Qaroshi_14_Desktop_Preview.png'),full_page=False)
 page.locator('[data-nav="translations"]').click();page.wait_for_selector('#find')
 ck('103 translation review queue',page.locator('#resultCount').inner_text().startswith('103'))
 page.locator('#priority').select_option('high');page.wait_for_timeout(60)
 ck('high-priority translation entries',page.locator('#results [data-id]').count()>0)
 page.locator('#find').fill('q12-a-price-too-low');page.wait_for_timeout(60)
 ck('translation search',page.locator('#results [data-id]').count()>0)
 page.locator('#results [data-id]').first.click();page.wait_for_selector('#decision')
 ck('source and English view',page.locator('.example').count()>0)
 ck('editorial proposal visible',page.locator('.section-label').filter(has_text='Proposed standalone English').count()==1)
 page.locator('#decision').select_option('needs_context');page.locator('#reviewnote').fill('Reviewed in contextual scene, no automatic acceptance.')
 page.locator('#saveReview').click();ck('review stored in UI', 'Saved' in page.locator('#saveResult').inner_text())
 page.locator('[data-nav="idioms"]').click();page.wait_for_selector('#find')
 ck('idiom queue 1000',page.locator('#resultCount').inner_text().startswith('1,000'))
 page.locator('#find').fill('wing_shelter');page.wait_for_timeout(60)
 ck('idiom family filter',page.locator('#results [data-id]').count()>0)
 page.locator('#results [data-id]').first.click();page.wait_for_selector('#decision')
 ck('idiom detail',page.locator('h1').inner_text()=='Proposed expression')
 page.locator('[data-nav="senses"]').click();page.wait_for_selector('#find')
 ck('sense queue 5000',page.locator('#resultCount').inner_text().startswith('5,000'))
 page.locator('#find').fill('daruhoho');page.wait_for_timeout(80)
 ck('specific sense search',page.locator('#results [data-id]').count()>0)
 page.locator('#results [data-id]').first.click();page.wait_for_selector('#decision')
 ck('sense detailed meaning',page.locator('.example').count()>0)
 page.locator('[data-nav="variants"]').click();page.wait_for_selector('#find')
 ck('115 source/English clusters',page.locator('#resultCount').inner_text().startswith('115'))
 page.locator('#find').fill('goro');page.wait_for_timeout(60)
 ck('variant filter',page.locator('#results [data-id]').count()>0)
 page.locator('#results [data-id]').first.click();page.wait_for_selector('.quote');ck('variant rendering detail',page.locator('.quote').count()>=2)
 page.locator('[data-nav="rules"]').click();page.wait_for_function('document.querySelectorAll(".rule-id").length===40');ck('20 registered decisions',page.locator('.rule-id').count()==40)
 page.locator('[data-nav="checker"]').click();page.wait_for_selector('#sentence')
 page.locator('#sentence').fill('sen mi goro-ki-ho.');page.locator('#english').fill('I am allowed to fly.');page.locator('#analyze').click()
 ck('invalid suffix detected', 'R14-005' in page.locator('#analysisResult').inner_text())
 page.locator('#sentence').fill('sen mi goro-ki.');page.locator('#english').fill('I fly.');page.locator('#analyze').click()
 ck('ability English gap explained','R14-012' in page.locator('#analysisResult').inner_text())
 page.locator('#sentence').fill('më mi ti-m nashi.');page.locator('#english').fill('I cherish you.');page.locator('#analyze').click()
 ck('valid simple example','No checked issues' in page.locator('#analysisResult').inner_text())
 page.locator('[data-nav="progress"]').click();ck('saved review count',page.locator('.metric').nth(1).locator('strong').inner_text()=='1')
 with page.expect_download(timeout=10000) as d:page.locator('#export').click()
 download=d.value
 ck('local JSON export',download.suggested_filename=='qaroshi_14_local_decisions.json')
 page.locator('#theme').click();ck('theme toggle',page.locator('html').get_attribute('data-theme')=='dark')
 mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
 mobile.on('pageerror',lambda e:errors.append(str(e)))
 mobile.set_content(HTML,wait_until='domcontentloaded',timeout=80000)
 ck('mobile home',mobile.locator('h1').count()==1)
 mobile.locator('#mobilemenu').click();ck('mobile navigation',mobile.locator('#sidebar.open').count()==1)
 mobile.locator('[data-nav="translations"]').click();mobile.wait_for_selector('#find');ck('mobile translation browser',mobile.locator('#results [data-id]').count()>0)
 mobile.screenshot(path=str(ROOT/'Qaroshi_14_Mobile_Preview.png'),full_page=False)
 browser.close()
print('BROWSER SUMMARY',sum(v for _,v in checks),'/',len(checks),'page errors',len(errors))
if errors:print('PAGE ERRORS',errors[:8])
if errors or not all(v for _,v in checks):raise SystemExit(1)
