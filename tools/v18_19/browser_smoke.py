#!/usr/bin/env python3
"""Local, offline navigation and cross-reference smoke tests for Qaroshi 18/19."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[2]
HTML=(ROOT/'Qaroshi_18_19_Living_Language_Studio.html').read_text(encoding='utf-8')
passed=[]
def ck(value,name):
 if not value:raise AssertionError(name)
 passed.append(name)
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-gpu'])
 for mode,viewport in [('desktop',{'width':1440,'height':900}),('mobile',{'width':390,'height':844})]:
  page=browser.new_page(viewport=viewport)
  errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  page.set_content(HTML,wait_until='domcontentloaded',timeout=90000)
  ck(page.locator('#stats .stat').count()==4,mode+' overview')
  ck(page.locator('[data-tab]').count()==6,mode+' six functional sections')
  page.locator('#tab-talk').wait_for(state='visible');ck(page.locator('#tab-talk').is_visible(),mode+' conversation entry')
  ck(page.locator('#talk-lines .word-link').count()>=3,mode+' clickable conversation words')
  page.locator('#talk-lines .word-link').first.click()
  page.locator('#tab-roots').wait_for(state='visible');ck(page.locator('#tab-roots').is_visible(),mode+' conversation to dictionary navigation')
  ck(page.locator('#word-detail .word-title').count()==1,mode+' dictionary detail')
  ck('#word/' in page.evaluate('location.hash'),mode+' meaningful word deep link')
  page.locator('#nav-back').click()
  page.locator('#tab-talk').wait_for(state='visible');ck(page.locator('#tab-talk').is_visible(),mode+' in-site back')
  page.locator('[data-tab="phrases"]').click()
  page.locator('#tab-phrases').wait_for(state='visible');ck(page.locator('#tab-phrases').is_visible(),mode+' phrase tab')
  ck(page.locator('#phrase-list .phrase-list-link').count()>=60,mode+' phrase index')
  page.locator('#phrase-search').fill('Thank you')
  ck(page.locator('#phrase-list .phrase-list-link').count()>=1,mode+' phrase search')
  page.locator('#phrase-list .phrase-list-link').first.click()
  ck('#phrase/' in page.evaluate('location.hash'),mode+' phrase deep link')
  ck(page.locator('#phrase-detail .word-link').count()>=1,mode+' phrase to word')
  ck(page.locator('#phrase-detail .related-group').count()>=1,mode+' related phrases or conversations')
  page.locator('#phrase-detail .word-link').first.click()
  page.locator('#tab-roots').wait_for(state='visible');ck(page.locator('#tab-roots').is_visible(),mode+' phrase to root navigation')
  page.locator('#global-search').fill('consent')
  ck(page.locator('#global-results').is_visible(),mode+' global search dropdown')
  ck(page.locator('#global-results a').count()>=4,mode+' unified references')
  page.locator('#global-results a[href^="#grammar/"]').first.click() if page.locator('#global-results a[href^="#grammar/"]').count() else page.locator('#global-results a').first.click()
  page.locator('#global-results').wait_for(state='hidden');ck(page.locator('#global-results').is_hidden(),mode+' global results close on navigation')
  page.locator('[data-tab="grammar"]').click()
  page.locator('#tab-grammar').wait_for(state='visible');ck(page.locator('#tab-grammar').is_visible(),mode+' grammar tab')
  ck(page.locator('#rule-body .word-link').count()>=1,mode+' grammar to lexicon links')
  page.locator('[data-tab="roots"]').click()
  page.locator('#lex-search').fill('wing')
  ck(page.locator('#lex-results .dictionary-link').count()>=3,mode+' canonical dictionary search')
  page.locator('#lex-results .dictionary-link').first.click()
  ck(page.locator('#word-detail .gloss').count()>=1,mode+' dictionary entry opened')
  page.locator('[data-tab="practice"]').click()
  page.locator('#tab-practice').wait_for(state='visible');ck(page.locator('#tab-practice').is_visible(),mode+' study nav')
  page.locator('#practice-reveal').click()
  ck(page.locator('#practice-card .word-link').count()>0,mode+' drill links to words')
  # Deep links work directly, even when the page was not reached via a tab.
  page.evaluate("location.hash='#word/babawayabikhimi'")
  page.locator('#word-detail').get_by_text('Documented dictionary components').wait_for()
  ck(page.locator('#word-detail .related-chips a[href="#word/babawaya"]').count()>=1,mode+' canonical compound component backlinks')
  page.locator('#word-detail .related-chips a[href="#word/babawaya"]').first.click()
  ck(page.locator('#word-detail h3').inner_text()=='babawaya',mode+' component-to-word route')
  page.evaluate("location.hash='#proposal/banuaro'")
  page.locator('#proposal-search').wait_for()
  ck(page.locator('#proposal-search').input_value()=='banuaro',mode+' root reform deep link')
  page.evaluate("location.hash='#grammar/G18-001'")
  page.locator('#rule-body h2').get_by_text('Written complete sentence').wait_for()
  ck(page.locator('#tab-grammar').is_visible(),mode+' grammar deep link')
  page.evaluate("location.hash='#phrase/S00001'")
  page.locator('#phrase-detail h2').get_by_text('Hello, friend!').wait_for()
  ck(page.locator('#phrase-detail .word-link').count()>=2,mode+' direct phrase link with lexical links')
  page.evaluate("location.hash='#talk/C18-001'")
  page.locator('#talk-head h2').get_by_text('First meeting').wait_for()
  ck(page.locator('#talk-lines .meta a[href="#phrase/S00001"]').count()==1,mode+' source ID to phrase backlink')
  page.locator('#global-search').press('Control+k')
  ck(page.locator('#global-search').evaluate('(e)=>document.activeElement===e'),mode+' keyboard search shortcut')
  page.locator('#global-search').fill('kima')
  ck(page.locator('#global-results a[href^="#word/"]').count()>=1,mode+' lexical search matches')
  page.locator('#global-search').press('Escape')
  ck(page.locator('#global-results').is_hidden(),mode+' escape collapses search')
  if mode=='mobile':
   boxes=page.locator('[data-tab]').evaluate_all('(tabs)=>tabs.map(e=>({left:e.getBoundingClientRect().left,right:e.getBoundingClientRect().right,top:e.getBoundingClientRect().top}))')
   ck(all(0<=x['left']<x['right']<=viewport['width'] for x in boxes),mode+' all six navigation buttons on screen')
   ck(len(set(round(x['top']) for x in boxes))==2,mode+' accessible two-row tab grid')
  ck(not errors,mode+' no JavaScript errors '+str(errors[:2]))
  page.locator('[data-tab="talk"]').click()
  if mode=='desktop':page.screenshot(path=str(ROOT/'Qaroshi_18_19_Desktop.png'),full_page=True)
  else:page.screenshot(path=str(ROOT/'Qaroshi_18_19_Mobile.png'),full_page=True)
  page.close()
 browser.close()
(ROOT/'data/v18_19_navigation_checks.json').write_text(json.dumps({'passed':True,'checks':len(passed),'items':passed},indent=2),encoding='utf-8')
print('PASSED',len(passed),'offline navigation/browser checks')
