"""15.1 Corpus Atlas browser smoke tests, including provenance separation."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[2]
HTML=(ROOT/'Qaroshi_15_Expanded_Corpus_Library.html').read_text(encoding='utf8')
checks=[];errors=[]
def ck(name,cond):
 checks.append({'test':name,'passed':bool(cond)})
 print(('PASS' if cond else 'FAIL'),name,flush=True)
with sync_playwright() as pw:
 b=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-web-security'])
 page=b.new_page(viewport={'width':1340,'height':900});page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content(HTML,wait_until='load',timeout=90000)
 ck('overview visible','A language in context' in page.locator('#app').inner_text())
 ck('count 1000','1,000' in page.locator('#app').inner_text())
 ck('honest provenance','824' in page.locator('#app').inner_text())
 page.locator('[data-nav="browse"]').click()
 ck('default original filter',page.locator('#originFilter').input_value()=='original')
 ck('original 211 pieces', '211 matching' in page.locator('#app').inner_text())
 page.locator('#originFilter').select_option('procedural')
 ck('procedural 994 pieces','994 matching' in page.locator('#app').inner_text())
 page.locator('#kindFilter').select_option('dialogue')
 ck('procedural dialogue 824','824 matching' in page.locator('#app').inner_text())
 page.locator('#kindFilter').select_option('literature')
 ck('procedural prose 170','170 matching' in page.locator('#app').inner_text())
 page.locator('#kindFilter').select_option('all')
 page.locator('[data-piece]').first.click()
 ck('transcript exists',page.locator('.line').count()>=20)
 ck('translations initially hidden',page.locator('.line .en:not(.hidden)').count()==0)
 page.locator('#translationToggle').click()
 ck('translations revealed',page.locator('.line .en:not(.hidden)').count()==page.locator('.line').count())
 page.locator('#reviewNote').fill('Check conditional scope before accepting this language.')
 page.locator('#saveNote').click()
 ck('review saved','Saved locally' in page.locator('#noteStatus').inner_text())
 page.locator('[data-word]').first.click()
 ck('lexeme details',page.locator('#wordDetail .word-detail').count()==1)
 page.locator('#concordanceFromWord').click()
 ck('concordance search',page.locator('.line').count()>1)
 page.locator('[data-nav="dictionary"]').click()
 page.locator('#dictionarySearch').fill('nashi')
 ck('dictionary results',page.locator('#dictionaryResults .line').count()>0)
 page.locator('[data-nav="quality"]').click()
 ck('quality evidence','over 100,000' in page.locator('#app').inner_text())
 page.locator('[data-nav="review"]').click()
 ck('review export',page.locator('#exportReview').count()==1)
 ck('no console page errors',not errors)
 page.screenshot(path=str(ROOT/'Qaroshi_15_Expanded_Desktop.png'),full_page=False)
 mobile=b.new_page(viewport={'width':390,'height':845},is_mobile=True);mobile.on('pageerror',lambda e:errors.append(str(e)))
 mobile.set_content(HTML,wait_until='load',timeout=90000)
 mobile.locator('#navToggle').click()
 ck('mobile navigation', 'open' in mobile.locator('#sidebar').get_attribute('class'))
 mobile.locator('[data-nav="browse"]').click()
 ck('mobile browser visible', mobile.locator('h1').count()==1)
 mobile.screenshot(path=str(ROOT/'Qaroshi_15_Expanded_Mobile.png'),full_page=False)
 b.close()
print('Browser checks',sum(x['passed'] for x in checks),'/',len(checks),'JS errors',errors)
(ROOT/'corpus/v15_completion/browser_test_report.json').write_text(json.dumps({'checks':checks,'errors':errors},indent=2),encoding='utf8')
if errors or any(not x['passed'] for x in checks):raise SystemExit(1)
