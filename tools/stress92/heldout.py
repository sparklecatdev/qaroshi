#!/usr/bin/env python3
"""450 new cross-family tests of exact, source-licensed event composition.

This is a *held-out-from-the-original-500* structural productivity benchmark,
not a new language sample independently generated by speakers. English labels
were separately authored and are not copied from the older English stimuli.
"""
from __future__ import annotations
import csv
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from tools.stress91.compose import build as build91, rows as csvrows

OUT = ROOT / "data/stress92"
SPEC = ROOT / "data/standard_9_2/heldout_events.json"
MOTION = ROOT / "data/standard_8/motion_frames_9_1.json"


def write(path: Path, records: list[dict]) -> None:
    assert records
    path.parent.mkdir(parents=True,exist_ok=True)
    with path.open("w", newline="", encoding="utf8") as file:
        writer = csv.DictWriter(file,fieldnames=list(records[0]),lineterminator="\n")
        writer.writeheader()
        writer.writerows(records)


def load() -> tuple[dict,dict[int,dict],dict[int,dict]]:
    spec=json.loads(SPEC.read_text(encoding="utf8"))
    frames={int(x["family"]):x for x in json.loads(MOTION.read_text(encoding="utf8"))}
    labels={int(x["family"]):x for x in spec["events"]}
    assert set(frames)==set(labels)==set(range(1,11))
    assert spec["relations"]==["after","before","when","reported_after","question_before"]
    return spec,frames,labels


def render(first:dict, second:dict, label1:dict, label2:dict, kind:str)->tuple[str,str]:
    p=first["main"]
    q=second["before"]
    spoken=label1["main_past"]
    endpoint=label2["endpoint_past"]
    if kind=="after":
        return f"sen ana {p}, {q}.", f"After {spoken}, {endpoint}."
    if kind=="before":
        return f"sen ëna {q}, {p}.", f"Before {endpoint}, {spoken}."
    if kind=="when":
        return f"sen yaro {q}, {p}.", f"When {endpoint}, {spoken}."
    if kind=="reported_after":
        return (f"sen ana {p}, {q} do yano mi-tu shiri-te.",
                f"Someone told me that after {spoken}, {endpoint}.")
    if kind=="question_before":
        return (f"hë ëna {q}, {p} he?",
                f"Did {label1['main_bare']} before {endpoint}?")
    raise ValueError(kind)


def build()->dict:
    # The authoritative comparison set is the *original English*, not a
    # fresh copy of the same source template. Do not modify either corpus.
    build91()
    original=csvrows(ROOT/"data/stress81/challenges_500.csv")
    prior=csvrows(ROOT/"data/stress91/case_evidence_500.csv")
    spec,frames,labels=load()
    excluded_english={r["english"].casefold() for r in original}
    excluded_qaroshi={r["qaroshi_full_candidate"] for r in prior}
    records=[]
    for main_id in sorted(frames):
        for boundary_id in sorted(frames):
            if main_id==boundary_id:
                continue
            for relation in spec["relations"]:
                first=frames[main_id]
                second=frames[boundary_id]
                candidate,english=render(first,second,labels[main_id],labels[boundary_id],relation)
                assert english.casefold() not in excluded_english
                assert candidate not in excluded_qaroshi
                row={
                    "id":f"H92-{len(records)+1:04d}",
                    "main_family":main_id,
                    "endpoint_family":boundary_id,
                    "relation":relation,
                    "english_novel_target":english,
                    "qaroshi_editorial_candidate":candidate,
                    "licensed_main_event":first["main"],
                    "licensed_endpoint_event":second["before"],
                    "matrix_event_asserted":str(relation not in ("reported_after","question_before")).lower(),
                    "indefinite_source_report":str(relation=="reported_after").lower(),
                    "direct_polar_question":str(relation=="question_before").lower(),
                    "implied_event_causation":"false",
                    "old_500_case_english_duplicate":"false",
                    "old_500_candidate_duplicate":"false",
                    "independently_understood_by_humans":"no",
                    "actual_human_backtranslation":"",
                }
                records.append(row)
    assert len(records)==spec["expected_sentences"]==450
    assert len({r["english_novel_target"] for r in records})==450
    assert len({r["qaroshi_editorial_candidate"] for r in records})==450
    report={
        "edition":"9.2 bounded held-out cross-family compositional stress",
        "original_frozen_stimuli":len(original),
        "novel_editorial_stimuli":len(records),
        "distinct_cross_family_event_pairs":len({(r["main_family"],r["endpoint_family"]) for r in records}),
        "relation_types":dict(sorted(Counter(r["relation"] for r in records).items())),
        "original_English_overlaps":0,
        "original_Qaroshi_overlaps":0,
        "scope_truth_conditions_tracked":True,
        "independent_comprehension_trials":0,
        "human_meaning_certified":0,
        "scope_limit":"The event content is licensed only in the supplied frames; pairs and connectors are novel. This is not a general unrestricted translation or grammar test.",
    }
    assert report["distinct_cross_family_event_pairs"]==90
    OUT.mkdir(parents=True,exist_ok=True)
    write(OUT/"unseen_compositions_450.csv",records)
    (OUT/"unseen_summary.json").write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf8")
    return report


if __name__=="__main__":
    print(json.dumps(build(),ensure_ascii=False,indent=2))
